    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {
        String accno = txtaccno.getText().trim(); // Trim spaces
        
        try {
            // 1. First check if account number is valid
            if (accno.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Please enter an account number");
                return;
            }
            
            // 2. Test database connection
            Class.forName("com.mysql.jdbc.Driver");
            con1 = DriverManager.getConnection("jdbc:mysql://localhost:3306/sanbank", System.getenv("BANK_DB_USER"), System.getenv("BANK_DB_PASSWORD"));
            System.out.println("Database connection successful");
            
            // 3. First run a simple query to verify table structure
            PreparedStatement checkStmt = con1.prepareStatement("SHOW TABLES");
            ResultSet tables = checkStmt.executeQuery();
            System.out.println("Tables in database:");
            while (tables.next()) {
                System.out.println(tables.getString(1));
            }
            
            // Add this debug code to print the exact table name case
            ResultSet tablesMetadata = con1.getMetaData().getTables(null, null, "%", null);
            while (tablesMetadata.next()) {
                System.out.println("Table name: " + tablesMetadata.getString(3));
            }
            
            // 4. Then try the account lookup query with lowercase table names
            String sql = "SELECT a.acc_id, c.cust_id, c.firstname, c.lastname, a.balance " +
                         "FROM Account a JOIN customer c ON a.cust_id = c.cust_id " +
                         "WHERE a.acc_id = ?";
            
            System.out.println("Executing query: " + sql + " with acc_id=" + accno);
            insert = con1.prepareStatement(sql);
            insert.setString(1, accno);
            rs1 = insert.executeQuery();

            if(rs1.next() == false) {
                System.out.println("No account found for accno=" + accno);
                JOptionPane.showMessageDialog(null, "Account Not found");
                txtfname.setText("");
                txtlame.setText("");
                lbal.setText("");
            } else {
                System.out.println("Account found!");
                String id = rs1.getString(2); // cust_id is now in column 2
                String firstname = rs1.getString(3);
                String laststname = rs1.getString(4);
                String balance = rs1.getString(5);

                jLabel7.setText(id.trim());
                txtfname.setText(firstname.trim());
                txtlame.setText(laststname.trim());
                lbal.setText(balance.trim());
            }
        } catch (Exception ex) {
            // More detailed error reporting
            ex.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error: " + ex.getMessage());
            System.out.println("Exception type: " + ex.getClass().getName());
            System.out.println("Stack trace:");
            for (StackTraceElement element : ex.getStackTrace()) {
                System.out.println("  " + element.toString());
            }
        }
    }

